def rag_response(query):

    # Retrieve relevant documents
    context = retrieve_context(query, k=3)

    # Construct an improved prompt
    prompt = f"""
      You are an e-commerce customer support assistant.

      Answer the customer's question using only the context below.

      Follow these instructions:
      1. Start with a direct answer.
      2. Present the steps in a clear numbered sequence.
      3. Explain automatic and manual refunds separately when relevant.
      4. Avoid repeating the same information.
      5. Use simple customer-friendly language.
      6. Do not invent information that is not in the context.
      7. If information is unavailable, clearly mention it.

      Context:
      {context}

      Customer Question:
      {query}

      Answer:
      """


    inputs = tokenizer(
        prompt,
        return_tensors="pt",
        truncation=True,
        max_length=512
    ).to(device)

    outputs = llm.generate(
        **inputs,
        max_new_tokens=200,
        do_sample=False,
        num_beams=4
    )

    response = tokenizer.decode(
        outputs[0],
        skip_special_tokens=True
    )

    return response

